import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, copyFileSync, existsSync, rmSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dbPath = join(root, 'seeker/data/seeker.sqlite');
if (!existsSync(dbPath)) throw new Error(`Seeker database not found: ${dbPath}`);
const db = new DatabaseSync(dbPath, { readOnly: true });
const rows = db.prepare(`SELECT e.id,e.title,e.event_date,e.event_end_date,e.event_time,e.venue,s.source_url,i.local_name,i.mime_type
 FROM events e JOIN event_sources s ON s.event_id=e.id AND s.source_key='vilnius-events'
 LEFT JOIN vilnius_events v ON CAST(v.source_id AS TEXT)=s.source_id
 LEFT JOIN vilnius_images i ON i.media_id=v.featured_media ORDER BY e.id`).all();
const artists = db.prepare(`SELECT a.mbid,a.name FROM event_artist_decisions d JOIN artists a ON a.mbid=d.artist_mbid WHERE d.event_id=? AND d.decision='accepted' ORDER BY a.name`);
const assets = join(root, 'client/assets/events');
const temp = join(root, 'client/assets/events-next');
rmSync(temp, {recursive:true,force:true}); mkdirSync(temp,{recursive:true});
const images = [];
const events = rows.map(({local_name,mime_type,...row}) => {
 let image = null;
 if (local_name) {
  const source = join(root,'seeker/data/images/vilnius-events',local_name);
  if (existsSync(source)) {
   const ext = {'image/jpeg':'jpg','image/png':'png','image/webp':'webp','image/gif':'gif'}[mime_type];
   if (ext) { const name = `${row.id}.${ext}`; copyFileSync(source,join(temp,name));
    if (process.platform === 'darwin' && ext !== 'gif') { try {
      execFileSync('sips',['--resampleHeightWidthMax','1200',join(temp,name)],{stdio:'ignore'});
      if (statSync(join(temp,name)).size > statSync(source).size) copyFileSync(source,join(temp,name));
    } catch { copyFileSync(source,join(temp,name)); } }
    image = row.id; images.push(`  ${row.id}: require('../../assets/events/${name}'),`);
   }
  }
 }
 return {...row, image, artists: artists.all(row.id)};
});
rmSync(assets,{recursive:true,force:true});
import { renameSync } from 'node:fs';
renameSync(temp,assets);
writeFileSync(join(root,'client/src/data/events.json'),JSON.stringify(events,null,2)+'\n');
writeFileSync(join(root,'client/src/data/event-images.ts'),`// Generated by npm run export:events.\nexport const eventImages: Record<number, number> = {\n${images.join('\n')}\n};\n`);
console.log(`Exported ${events.length} events and ${images.length} images.`);
